@dataclasses.dataclass(frozen=True)
class PyFuncInfo:
    name: str
    is_async: bool
    signature: str


@dataclasses.dataclass(frozen=True)
class PyClassInfo:
    name: str
    is_enum: bool
    constructors: list[str]
    properties: list[tuple[str, str]]
    methods: list[tuple[str, str]]
    enum_members: list[tuple[str, str]]


def _format_py_func_sig(node: ast.FunctionDef | ast.AsyncFunctionDef, *, drop_self: bool = False) -> str:
    fn_copy = ast.fix_missing_locations(
        ast.FunctionDef(
            name=node.name,
            args=node.args,
            body=[ast.Expr(value=ast.Constant(value=...))],
            decorator_list=[],
            returns=node.returns,
            type_params=getattr(node, "type_params", []),
        )
    )
    raw = ast.unparse(fn_copy)
    header = raw.splitlines()[0].rstrip(":")
    if isinstance(node, ast.AsyncFunctionDef):
        header = "async " + header
    if drop_self:
        header = re.sub(r"\((?:self|cls),\s*/,\s*", "(", header)
        header = re.sub(r"\((?:self|cls),\s*/\)", "()", header)
        header = re.sub(r"\((?:self|cls),\s*", "(", header)
        header = re.sub(r"\((?:self|cls)\)", "()", header)
    return header


def parse_python_pyi(pyi_path: pathlib.Path) -> tuple[list[PyFuncInfo], dict[str, PyClassInfo]]:
    tree = ast.parse(pyi_path.read_text(encoding="utf-8"))
    funcs: list[PyFuncInfo] = []
    classes: dict[str, PyClassInfo] = {}

    for node in tree.body:
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)) and not node.name.startswith("_"):
            funcs.append(
                PyFuncInfo(
                    name=node.name,
                    is_async=isinstance(node, ast.AsyncFunctionDef),
                    signature=_format_py_func_sig(node, drop_self=False),
                )
            )
        elif isinstance(node, ast.ClassDef) and not node.name.startswith("_"):
            base_names = [ast.unparse(b) for b in node.bases]
            is_enum = "Enum" in base_names
            ctors: list[str] = []
            props: list[tuple[str, str]] = []
            methods: list[tuple[str, str]] = []
            enum_members: list[tuple[str, str]] = []

            for item in node.body:
                if is_enum and isinstance(item, ast.Assign):
                    for t in item.targets:
                        if isinstance(t, ast.Name):
                            enum_members.append((t.id, ast.unparse(item.value)))
                elif isinstance(item, (ast.FunctionDef, ast.AsyncFunctionDef)):
                    decos = {ast.unparse(d) for d in item.decorator_list}
                    if item.name == "__new__":
                        sig = _format_py_func_sig(item, drop_self=True)
                        sig = sig.replace("def __new__(", f"class {node.name}(")
                        ctors.append(sig)
                    elif "property" in decos:
                        ret = ast.unparse(item.returns) if item.returns else "Any"
                        props.append((item.name, ret))
                    elif item.name in ("__enter__", "__aenter__", "__iter__", "__aiter__", "__bool__", "__buffer__"):
                        methods.append((item.name, _format_py_func_sig(item, drop_self=True)))
                    elif not item.name.startswith("_"):
                        prefix = "@staticmethod\n" if "staticmethod" in decos else ""
                        methods.append((item.name, prefix + _format_py_func_sig(item, drop_self=("staticmethod" not in decos))))

            classes[node.name] = PyClassInfo(
                name=node.name,
                is_enum=is_enum,
                constructors=ctors,
                properties=props,
                methods=methods,
                enum_members=enum_members,
            )

    return funcs, classes


def _render_py_class(cls: PyClassInfo) -> str:
    desc = PYTHON_DESCRIPTIONS.get(cls.name, f"Frozen native `{cls.name}` class.")
    lines = [f"### `{cls.name}`\n", f"{desc}\n"]
    if cls.constructors:
        lines.append(_ignore_code_block("python", "\n".join(cls.constructors)))
    if cls.properties:
        lines.append("| Property | Type |")
        lines.append("| --- | --- |")
        for pname, ptype in cls.properties:
            lines.append(f"| `{pname}` | `{_md_escape_table(ptype)}` |")
        lines.append("")
    if cls.methods:
        lines.append(_ignore_code_block("python", "\n".join(sig for _, sig in cls.methods)))
    return "\n".join(lines) + "\n"


