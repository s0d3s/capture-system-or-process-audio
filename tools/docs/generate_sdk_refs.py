@dataclasses.dataclass(frozen=True)
class RustItemInfo:
    name: str
    kind: str  # 'fn', 'type', 'trait', 'struct', 'enum', 'mod'
    doc: str
    signature: str = ""

    @property
    def rustdoc_url(self) -> str:
        if self.kind == "mod":
            return f"{RUSTDOC_BASE}/capture_system_or_process_audio_core/{self.name}/index.html"
        return f"{RUSTDOC_BASE}/capture_system_or_process_audio/{self.kind}.{self.name}.html"


def _collect_core_rust_kinds_and_docs(core_src: pathlib.Path) -> tuple[dict[str, str], dict[str, str]]:
    kinds: dict[str, str] = {}
    docs: dict[str, str] = {}
    decl_re = re.compile(r"^\s*pub\s+(struct|enum|trait|type)\s+([A-Za-z_][A-Za-z0-9_]*)\b")

    for rs_file in sorted(core_src.rglob("*.rs")):
        lines = rs_file.read_text(encoding="utf-8").splitlines()
        doc_buf: list[str] = []
        for line in lines:
            stripped = line.strip()
            if stripped.startswith("///"):
                doc_buf.append(stripped[3:].strip())
                continue
            if stripped.startswith("#["):
                continue
            m = decl_re.match(line)
            if m:
                k, sym = m.group(1), m.group(2)
                kinds[sym] = k
                if doc_buf:
                    docs[sym] = " ".join(doc_buf)
            doc_buf = []
    return kinds, docs


def parse_rust_facade(workspace_root: pathlib.Path) -> list[RustItemInfo]:
    lib_rs = (workspace_root / "crates" / "capture" / "src" / "lib.rs").read_text(encoding="utf-8")
    core_kinds, core_docs = _collect_core_rust_kinds_and_docs(workspace_root / "crates" / "capture-core" / "src")

    items: dict[str, RustItemInfo] = {}

    # 1. Re-exported items from `pub use core::...::{...};`
    for m in re.finditer(r"pub\s+use\s+core(?:::([a-z_]+))?::\{([^}]+)\};", lib_rs, re.DOTALL):
        for raw_tok in m.group(2).split(","):
            tok = raw_tok.strip()
            if not tok:
                continue
            if tok[0].islower():
                items[tok] = RustItemInfo(
                    name=tok,
                    kind="mod",
                    doc=f"Re-exported `capture_system_or_process_audio_core::{tok}` module.",
                )
            else:
                k = core_kinds.get(tok, "struct")
                d = core_docs.get(tok, f"Re-exported `{tok}` {k} from `capture-system-or-process-audio-core`.")
                items[tok] = RustItemInfo(name=tok, kind=k, doc=d)

    # 2. Top-level `pub type` and `pub fn` in crates/capture/src/lib.rs
    lines = lib_rs.splitlines()
    idx = 0
    while idx < len(lines):
        stripped = lines[idx].strip()
        if stripped.startswith("#[cfg(test)]"):
            break
        doc_buf: list[str] = []
        while idx < len(lines) and lines[idx].strip().startswith("///"):
            doc_buf.append(lines[idx].strip()[3:].strip())
            idx += 1
        while idx < len(lines) and lines[idx].strip().startswith("#[") and not lines[idx].strip().startswith("#[cfg(test)]"):
            idx += 1
        if idx >= len(lines):
            break
        line = lines[idx]
        m_type = re.match(r"^pub\s+type\s+([A-Za-z_][A-Za-z0-9_]*)\s*=\s*([^;]+);", line)
        if m_type:
            name = m_type.group(1)
            items[name] = RustItemInfo(
                name=name,
                kind="type",
                doc=" ".join(doc_buf) or f"Facade type alias `{name}`.",
                signature=line.strip(),
            )
            idx += 1
            continue
        m_fn = re.match(r"^pub\s+fn\s+([a-z_][a-z0-9_]*)\b", line)
        if m_fn:
            name = m_fn.group(1)
            sig_lines = [line.rstrip()]
            while "{" not in sig_lines[-1] and idx + 1 < len(lines):
                idx += 1
                sig_lines.append(lines[idx].rstrip())
            sig = "\n".join(sig_lines).split("{", 1)[0].rstrip()
            items[name] = RustItemInfo(
                name=name,
                kind="fn",
                doc=" ".join(doc_buf) or f"Top-level `{name}` facade function.",
                signature=sig,
            )
        idx += 1

    return list(items.values())


