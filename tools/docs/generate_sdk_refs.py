@dataclasses.dataclass(frozen=True)
class CppEnumInfo:
    name: str
    underlying: str
    members: list[tuple[str, str]]


@dataclasses.dataclass(frozen=True)
class CppClassInfo:
    name: str
    kind: str  # 'class' or 'struct'
    template_prefix: str
    public_synopsis: str


@dataclasses.dataclass(frozen=True)
class CppFuncInfo:
    name: str
    signature: str


def _extract_brace_block(text: str, open_brace_idx: int) -> tuple[str, int]:
    depth = 0
    i = open_brace_idx
    while i < len(text):
        ch = text[i]
        if ch == "{":
            depth += 1
        elif ch == "}":
            depth -= 1
            if depth == 0:
                return text[open_brace_idx + 1 : i], i + 1
        i += 1
    raise ValueError("Unbalanced braces in C/C++ header")


def _build_cpp_public_synopsis(kind: str, name: str, template_prefix: str, inheritance: str, body: str) -> str:
    """Keep public declarations & #if CSPA_HAS_EXCEPTIONS blocks while collapsing method bodies to `;`."""
    vis = "public" if kind == "struct" else "private"
    out_lines: list[str] = []
    header = (f"{template_prefix}\n" if template_prefix else "") + f"{kind} {name}{inheritance} {{"
    out_lines.append(header)
    if kind == "class":
        out_lines.append("public:")

    i = 0
    lines = body.splitlines()
    while i < len(lines):
        raw_line = lines[i]
        stripped = raw_line.strip()
        if not stripped:
            i += 1
            continue
        if stripped in ("public:", "private:", "protected:"):
            vis = stripped[:-1]
            i += 1
            continue
        if stripped.startswith("#if") or stripped.startswith("#endif") or stripped.startswith("#else"):
            out_lines.append(stripped)
            i += 1
            continue
        if vis != "public":
            # Skip any nested braces inside private section
            brace_delta = raw_line.count("{") - raw_line.count("}")
            while brace_delta > 0 and i + 1 < len(lines):
                i += 1
                brace_delta += lines[i].count("{") - lines[i].count("}")
            i += 1
            continue

        # Public member or field: collect until `;` or `{ ... }` at depth 0
        decl_lines = [raw_line]
        joined = raw_line
        while True:
            # Check if field initializer `{}` or `= ...;` without function body
            # Count parens first so multi-line parameter lists finish
            if joined.count("(") > joined.count(")"):
                i += 1
                decl_lines.append(lines[i])
                joined = "\n".join(decl_lines)
                continue
            # Does this declaration have a `{` function body after `)` (or `noexcept` / `const`)?
            after_parens = joined.rsplit(")", 1)[-1] if ")" in joined else ""
            if "(" in joined and "{" in after_parens:
                # Collapse inline method body `{ ... }` to `;`
                sig_only = joined[: len(joined) - len(after_parens)] + after_parens.split("{", 1)[0].rstrip() + ";"
                brace_delta = joined.count("{") - joined.count("}")
                while brace_delta > 0 and i + 1 < len(lines):
                    i += 1
                    brace_delta += lines[i].count("{") - lines[i].count("}")
                for sl in sig_only.splitlines():
                    out_lines.append("    " + sl.strip())
                break
            if stripped.endswith(";") or joined.rstrip().endswith(";"):
                for sl in decl_lines:
                    out_lines.append("    " + sl.strip())
                break
            i += 1
            if i >= len(lines):
                break
            decl_lines.append(lines[i])
            joined = "\n".join(decl_lines)
        i += 1

    out_lines.append("};")
    return "\n".join(out_lines)


def parse_cpp_header(hpp_path: pathlib.Path) -> tuple[list[CppEnumInfo], dict[str, CppClassInfo], list[CppFuncInfo]]:
    text = hpp_path.read_text(encoding="utf-8")
    enums: list[CppEnumInfo] = []
    classes: dict[str, CppClassInfo] = {}
    funcs: list[CppFuncInfo] = []

    for m in re.finditer(r"enum\s+class\s+([A-Za-z_][A-Za-z0-9_]*)\s*:\s*([A-Za-z0-9_]+)\s*\{", text):
        ename, underlying = m.group(1), m.group(2)
        body, _ = _extract_brace_block(text, m.end() - 1)
        members: list[tuple[str, str]] = []
        for line in body.splitlines():
            line = line.strip().rstrip(",")
            if "=" in line:
                k, v = line.split("=", 1)
                members.append((k.strip(), v.strip()))
        enums.append(CppEnumInfo(name=ename, underlying=underlying, members=members))

    cls_re = re.compile(
        r"^[ \t]*(?:(template\s*<[^>]+>)\s*)?(class|struct)\s+([A-Za-z_][A-Za-z0-9_]*)(\s*:\s*[^{]+)?\s*\{",
        re.MULTILINE,
    )
    pos = 0
    while True:
        m = cls_re.search(text, pos)
        if not m:
            break
        tmpl = (m.group(1) or "").strip()
        kind = m.group(2)
        cname = m.group(3)
        inh = (m.group(4) or "").rstrip()
        body, end_idx = _extract_brace_block(text, m.end() - 1)
        pos = end_idx
        classes[cname] = CppClassInfo(
            name=cname,
            kind=kind,
            template_prefix=tmpl,
            public_synopsis=_build_cpp_public_synopsis(kind, cname, tmpl, inh, body),
        )

    fn_re = re.compile(r"(?:(template\s*<[^>]+>)\s*)?inline\s+([A-Za-z0-9_:<>\s&*]+?)\s+([a-z_][a-z0-9_]*)\s*\(")
    pos = 0
    while True:
        m = fn_re.search(text, pos)
        if not m:
            break
        fn_name = m.group(3)
        open_brace = text.find("{", m.end())
        _, end_idx = _extract_brace_block(text, open_brace)
        sig_raw = text[m.start() : open_brace].rstrip() + ";"
        sig = "\n".join(ln.strip() for ln in sig_raw.splitlines())
        funcs.append(CppFuncInfo(name=fn_name, signature=sig))
        pos = end_idx

    return enums, classes, funcs


