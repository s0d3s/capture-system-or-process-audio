@dataclasses.dataclass(frozen=True)
class CStructInfo:
    name: str
    declaration: str
    fields: list[tuple[str, str]]
    sizeof_bytes: int | None
    offsets: list[tuple[str, int]]


@dataclasses.dataclass(frozen=True)
class CFuncInfo:
    name: str
    declaration: str


def parse_c11_header_and_layout(
    h_path: pathlib.Path,
    smoke_c_path: pathlib.Path,
) -> tuple[list[tuple[str, str]], list[str], list[CStructInfo], list[str], list[CFuncInfo]]:
    h_text = h_path.read_text(encoding="utf-8")
    smoke_text = smoke_c_path.read_text(encoding="utf-8")

    sizeof_map: dict[str, int] = {}
    for m in re.finditer(r"CHECK\(sizeof\((cspa_[a-z0-9_]+)\)\s*==\s*([0-9]+)u", smoke_text):
        sizeof_map[m.group(1)] = int(m.group(2))

    offset_map: dict[str, list[tuple[str, int]]] = {}
    for m in re.finditer(r"CHECK\(offsetof\((cspa_[a-z0-9_]+),\s*([a-z0-9_]+)\)\s*==\s*([0-9]+)u", smoke_text):
        offset_map.setdefault(m.group(1), []).append((m.group(2), int(m.group(3))))

    macros: list[tuple[str, str]] = []
    for m in re.finditer(r"^#define\s+(CSPA_[A-Z0-9_]+)(?:\s+(.+))?$", h_text, re.MULTILINE):
        m_name = m.group(1)
        m_val = (m.group(2) or "").strip()
        macros.append((m_name, m_val))

    opaque_handles: list[str] = []
    for m in re.finditer(r"^typedef\s+struct\s+(cspa_[a-z0-9_]+)\s+\1\s*;", h_text, re.MULTILINE):
        opaque_handles.append(m.group(1))

    structs: list[CStructInfo] = []
    for m in re.finditer(r"^typedef\s+struct\s+(cspa_[a-z0-9_]+)\s*\{", h_text, re.MULTILINE):
        sname = m.group(1)
        body, end_brace = _extract_brace_block(h_text, m.end() - 1)
        semi = h_text.find(";", end_brace)
        full_decl = h_text[m.start() : semi + 1].strip()
        fields: list[tuple[str, str]] = []
        for fline in body.splitlines():
            fline = fline.strip().rstrip(";")
            if not fline:
                continue
            # Split C type and field name/array
            fm = re.match(r"^(.+?)\s*(\*?[a-z0-9_]+(?:\[[^\]]+\])?)$", fline)
            if fm:
                ftype = fm.group(1).strip()
                fname = fm.group(2).strip()
                if fname.startswith("*"):
                    ftype += " *"
                    fname = fname[1:]
                fields.append((fname, ftype))
        structs.append(
            CStructInfo(
                name=sname,
                declaration=full_decl,
                fields=fields,
                sizeof_bytes=sizeof_map.get(sname),
                offsets=offset_map.get(sname, []),
            )
        )

    callbacks: list[str] = []
    for m in re.finditer(r"^typedef\s+[^;]+\(\*cspa_[a-z0-9_]+_fn\)\([^;]+\);", h_text, re.MULTILINE | re.DOTALL):
        callbacks.append(m.group(0).strip())

    funcs: list[CFuncInfo] = []
    for m in re.finditer(
        r"^(?:(?:uint32_t|void)\s+|cspa_owner\s*\*\s*)(cspa_[a-z0-9_]+)\s*\([^;]*\);",
        h_text,
        re.MULTILINE,
    ):
        fn_name = m.group(1)
        if fn_name.startswith("cspa_test_"):
            continue
        funcs.append(CFuncInfo(name=fn_name, declaration=m.group(0).strip()))

    return macros, opaque_handles, structs, callbacks, funcs


