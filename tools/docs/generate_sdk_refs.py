def generate_all_ref_pages(workspace_root: pathlib.Path = REPO_ROOT) -> dict[str, str]:
    pages: dict[str, str] = {}
    pages.update(build_python_ref_pages(workspace_root))
    pages.update(build_rust_ref_pages(workspace_root))
    pages.update(build_cpp_ref_pages(workspace_root))
    pages.update(build_c11_ref_pages(workspace_root))
    return pages


def sync_or_check_ref_pages(
    output_dir: pathlib.Path,
    *,
    workspace_root: pathlib.Path = REPO_ROOT,
    check_only: bool = False,
) -> list[str]:
    expected = generate_all_ref_pages(workspace_root)
    diffs: list[str] = []

    managed_subdirs = ("python", "rust", "cpp", "c")
    existing_rel: set[str] = set()
    for sub in managed_subdirs:
        sub_path = output_dir / sub
        if sub_path.is_dir():
            for f in sorted(sub_path.rglob("*")):
                if f.is_file() and f.suffix.lower() in (".md", ".mdx"):
                    existing_rel.add(f.relative_to(output_dir).as_posix())

    for extra in sorted(existing_rel - set(expected)):
        diffs.append(f"Stale unexpected reference file: {extra}")

    for rel_path, content in sorted(expected.items()):
        target = output_dir / rel_path
        expected_bytes = content.encode("utf-8")
        if check_only:
            if not target.is_file():
                diffs.append(f"Missing generated reference file: {rel_path}")
            elif target.read_bytes() != expected_bytes:
                diffs.append(f"Out-of-date reference file (differs from source of truth): {rel_path}")
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            if not target.is_file() or target.read_bytes() != expected_bytes:
                target.write_bytes(expected_bytes)

    if not check_only:
        for extra in sorted(existing_rel - set(expected)):
            (output_dir / extra).unlink()

    return diffs


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Generate or check deterministic multi-SDK Starlight API reference pages.")
    parser.add_argument(
        "--output-dir",
        type=pathlib.Path,
        default=DEFAULT_REF_DIR,
        help="Target reference docs directory (default: website/src/content/docs/reference).",
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="Verify generated files on disk match workspace headers/stubs byte-for-byte without writing.",
    )
    args = parser.parse_args(argv)

    diffs = sync_or_check_ref_pages(args.output_dir, workspace_root=REPO_ROOT, check_only=args.check)
    if diffs:
        for d in diffs:
            print(f"ERROR: {d}", file=sys.stderr)
        print("Run `python tools/docs/generate_sdk_refs.py` to regenerate reference docs.", file=sys.stderr)
        return 1

    mode = "verified (--check, 0 byte diff)" if args.check else "generated"
    print(f"OK: {len(generate_all_ref_pages(REPO_ROOT))} SDK reference pages {mode} at {args.output_dir.as_posix()}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
