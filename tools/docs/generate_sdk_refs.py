def _frontmatter(title: str, description: str) -> str:
    assert len(title) <= 65, f"Title too long ({len(title)}): {title}"
    assert 40 <= len(description) <= 175, f"Description length {len(description)} out of [40, 175]: {description}"
    return f"---\ntitle: \"{title}\"\ndescription: \"{description}\"\n---\n\n{GENERATED_BANNER}\n"


def _ignore_code_block(lang: str, code: str) -> str:
    clean = code.rstrip()
    return f"{{/* cspa-snippet: ignore */}}\n```{lang}\n{clean}\n```\n"


def _md_escape_table(cell: str) -> str:
    return cell.replace("|", "\\|").replace("\n", " ").strip()


